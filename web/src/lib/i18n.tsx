export function detectErrorText(lang: Lang, code: string | null, fallback: string | null, existingName?: string): string {
  const status = /HTTP \d+/.exec(fallback ?? "")?.[0];
  if (lang === "en") {
    switch (code) {
      case "exists":
        return existingName ? `Already registered as "${existingName}".` : "Endpoint is already registered.";
      case "invalid_url":
        return "URL must start with https:// and include a valid hostname.";
      case "https_required":
        return "Only https:// URLs are supported.";
      case "unreachable":
        return "Could not connect to endpoint. Check that flexsds serve is running.";
      case "blocked_address":
        return "Private or internal network addresses are not allowed.";
      case "not_ready":
        return `Endpoint not ready${status ? ` (${status})` : ""}. The GPU may still be starting.`;
      case "bad_response":
        return `Invalid OpenAI-compatible response from /v1/models${status ? ` (${status})` : ""}.`;
      case "no_model":
        return "No active model reported by /v1/models.";
      case "auth_failed":
        return `Authentication failed${status ? ` (${status})` : ""}.`;
      default:
        return fallback ?? "Verification failed.";
    }
  }
  switch (code) {
    case "exists":
      return existingName ? `Địa chỉ này đã tồn tại với alias "${existingName}".` : "Địa chỉ này đã tồn tại trong danh sách.";
    case "invalid_url":
      return "Địa chỉ phải bắt đầu bằng https:// và có tên miền hợp lệ.";
    case "https_required":
      return "Chỉ hỗ trợ địa chỉ https://.";
    case "unreachable":
      return "Không kết nối được tới endpoint. Kiểm tra lại phiên flexsds serve.";
    case "blocked_address":
      return "Không hỗ trợ địa chỉ mạng nội bộ.";
    case "not_ready":
      return `Endpoint chưa sẵn sàng${status ? ` (${status})` : ""}. GPU có thể đang khởi động.`;
    case "bad_response":
      return `Phản hồi từ /v1/models không hợp lệ${status ? ` (${status})` : ""}.`;
    case "no_model":
      return "Endpoint chưa phục vụ mô hình nào.";
    case "auth_failed":
      return `API key không hợp lệ${status ? ` (${status})` : ""}.`;
    default:
      return fallback ?? "Kiểm tra thất bại.";
  }
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Dict;
}

const I18nContext = createContext<I18nValue>({
  lang: "vi",
  setLang: () => undefined,
  t: TRANSLATIONS.vi,
});

export function I18nProvider({ children, initialLang }: { children: ReactNode; initialLang?: Lang }) {
  const [lang, setLangState] = useState<Lang>(() => initialLang ?? readStoredLang());

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    saveStoredLang(next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: TRANSLATIONS[lang] as Dict,
  }), [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
